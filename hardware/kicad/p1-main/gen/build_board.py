MM = pcbnew.FromMM
BAY = ("J1", "J2", "J3")
NETCLASSES = {  # clearance, track, via, drill (mirrors gen_pro.CLASSES)
    "Default": (0.15, 0.20, 0.60, 0.30), "PRI": (0.30, 0.30, 0.80, 0.40), "PWR": (0.15, 0.30, 0.80, 0.40),
    "AMP": (0.15, 0.40, 0.80, 0.40), "ETH": (0.15, 0.25, 0.60, 0.30), "USB": (0.15, 0.25, 0.60, 0.30),
}


def V(x, y):
    kx, ky = layout.k(x, y)
    return pcbnew.VECTOR2I(MM(kx), MM(ky))


def G(v):
    return layout.g(pcbnew.ToMM(v.x), pcbnew.ToMM(v.y))


def bbox_g(bb):
    x0, y1 = G(pcbnew.VECTOR2I(bb.GetLeft(), bb.GetTop()))
    x1, y0 = G(pcbnew.VECTOR2I(bb.GetRight(), bb.GetBottom()))
    return [round(x0, 3), round(y0, 3), round(x1, 3), round(y1, 3)]


# ---------------------------------------------------------------- board skeleton
def seg(board, layer, a, b, w=0.1):
    s = pcbnew.PCB_SHAPE(board)
    s.SetShape(pcbnew.SHAPE_T_SEGMENT)
    s.SetStart(V(*a)); s.SetEnd(V(*b))
    s.SetLayer(layer); s.SetWidth(MM(w))
    board.Add(s)


def rect(board, layer, x0, y0, x1, y1, w=0.1):
    for a, b in (((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))):
        seg(board, layer, a, b, w)


def read_netlist():
    t = kilib.parse(open(os.path.join(BUILD, "p1.net")).read())
    out = {}
    for n in kilib.find(kilib.first(t, "nets"), "net"):
        name = kilib.sval(kilib.first(n, "name")[1])
        for nd in kilib.find(n, "node"):
            out[(kilib.sval(kilib.first(nd, "ref")[1]), kilib.sval(kilib.first(nd, "pin")[1]))] = name
    return out


PADNET = read_netlist()


def skeleton():
    board = pcbnew.BOARD()
    board.SetCopperLayerCount(4)
    ds = board.GetDesignSettings()
    ds.SetCopperLayerCount(4)
    ns = ds.m_NetSettings
    for name, (cl, tr, vd, vh) in NETCLASSES.items():
        nc = ns.GetDefaultNetclass() if name == "Default" else pcbnew.NETCLASS(name)
        nc.SetClearance(MM(cl)); nc.SetTrackWidth(MM(tr)); nc.SetViaDiameter(MM(vd)); nc.SetViaDrill(MM(vh))
        if name != "Default":
            ns.SetNetclass(name, nc)
    for cls, nets in circuit.NETCLASS.items():
        for n in nets:
            ns.SetNetclassPatternAssignment(n, cls)
    ds.m_MinClearance = MM(0.15); ds.m_TrackMinWidth = MM(0.15); ds.m_ViasMinSize = MM(0.5)
    ds.m_MinThroughDrill = MM(0.2); ds.m_CopperEdgeClearance = MM(0.3); ds.m_HoleClearance = MM(0.25)
    ds.m_HoleToHoleMin = MM(0.25)
    rect(board, pcbnew.Edge_Cuts, layout.X0, layout.Y0, layout.X1, layout.Y1)
    for s in layout.SLOTS:
        rect(board, pcbnew.Edge_Cuts, *s)
    nets = {}
    for n in sorted(set(PADNET.values())):
        ni = pcbnew.NETINFO_ITEM(board, n)
        board.Add(ni)
        nets[n] = ni
    tb = board.GetTitleBlock()
    tb.SetTitle("AudioPicture P1 MAIN"); tb.SetRevision("P1.0"); tb.SetCompany("Cinetyk"); tb.SetDate("2026-10-23")
    tb.SetComment(0, "Generated by hardware/kicad/p1-main/gen - do not edit by hand")
    return board, nets


# ---------------------------------------------------------------- footprints
def make_fp(board, nets, p):
    fp = load(p["fp"])
    lib, _, name = p["fp"].partition(":")
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    fp.SetReference(p["ref"])
    fp.SetValue(p["value"])
    ds = kilib.prop(p["sym"], "Datasheet") or ""
    ds = "" if ds == "~" else ds
    fp.GetField(pcbnew.FIELD_T_DATASHEET).SetText(ds)
    for key, val in (("MPN", p["mpn"]), ("Note", p["note"])):
        if val or key == "MPN":
            f = pcbnew.PCB_FIELD(fp, pcbnew.FIELD_T_USER, key)
            f.SetText(val); f.SetVisible(False); f.SetLayer(pcbnew.F_Fab)
            fp.Add(f)
    for pad in fp.Pads():
        n = PADNET.get((p["ref"], pad.GetNumber()))
        if n and pad.GetNumber():
            pad.SetNet(nets[n])
        if pad.GetAttribute() == pcbnew.PAD_ATTRIB_PTH and (pad.GetDrillSize().x < MM(0.5) or pad.GetNumber() in ("MP", "SH")):
            pad.SetLocalZoneConnection(pcbnew.ZONE_CONNECTION_FULL)   # thermal vias in exposed pads
    ref = fp.Reference()
    ref.SetLayer(pcbnew.F_Fab)
    ref.SetTextSize(pcbnew.VECTOR2I(MM(0.6), MM(0.6))); ref.SetTextThickness(MM(0.09))
    ref.SetPosition(fp.GetPosition())
    board.Add(fp)
    return fp


def courtyard(fp):
    lay = pcbnew.B_CrtYd if fp.IsFlipped() else pcbnew.F_CrtYd
    cy = fp.GetCourtyard(lay)
    return cy.BBox() if cy.OutlineCount() else fp.GetBoundingBox(False)


def pad_centroid(fp):
    ps = [G(p.GetPosition()) for p in fp.Pads() if p.GetNumber()]
    return sum(x for x, _ in ps) / len(ps), sum(y for _, y in ps) / len(ps)


def place_fixed(fp, p):
    ref = p["ref"]
    at, rot = p["at"], p["rot"]
    if ref in layout.FIXED_EXTRA:
        at, rot = layout.FIXED_EXTRA[ref]
    fp.SetPosition(V(*at))
    if p["side"] == "B":
        fp.Flip(fp.GetPosition(), pcbnew.FLIP_DIRECTION_TOP_BOTTOM)
    if ref in BAY:
        # mating face toward -Y: choose the rotation whose courtyard reaches farthest below the pads
        best = None
        for r in (0, 90, 180, 270):
            fp.SetOrientationDegrees(r)
            cx, cy = pad_centroid(fp)
            x0, y0, x1, y1 = bbox_g(courtyard(fp))
            score = (cy - y0) - (y1 - cy)
            if best is None or score > best[0]:
                best = (score, r)
        fp.SetOrientationDegrees(best[1])
        x0, y0, x1, y1 = bbox_g(courtyard(fp))
        dx, dy = at[0] - (x0 + x1) / 2, at[1] - y0
        fp.Move(pcbnew.VECTOR2I(MM(dx), MM(-dy)))
    elif ref == "J5":
        fp.SetOrientationDegrees(rot)
        x0, y0, x1, y1 = bbox_g(courtyard(fp))
        fp.Move(pcbnew.VECTOR2I(MM(at[0] - (x0 + x1) / 2), MM(-(at[1] - (y0 + y1) / 2))))
    elif ref == "T1":
        for r in (90, 270):
            fp.SetOrientationDegrees(r)
            pads = {q.GetNumber(): G(q.GetPosition()) for q in fp.Pads()}
            if pads["1"][0] < pads["24"][0]:
                break
    elif ref == "U8":
        for r in (0, 90, 180, 270):
            fp.SetOrientationDegrees(r)
            cx, cy = pad_centroid(fp)
            x0, y0, x1, y1 = bbox_g(courtyard(fp))
            if (y1 - cy) > (cy - y0) + 5:
                break
        boxes = [bbox_g(it.GetBoundingBox()) for it in fp.GraphicalItems()
                 if it.GetLayer() == pcbnew.F_Fab and it.GetClass() == "PCB_SHAPE"]
        x0, y0 = min(b[0] for b in boxes), min(b[1] for b in boxes)
        x1, y1 = max(b[2] for b in boxes), max(b[3] for b in boxes)
        fp.Move(pcbnew.VECTOR2I(MM(at[0] - (x0 + x1) / 2), MM(-(at[1] - y1))))   # module antenna end flush with the top edge
    elif ref in ("SW1", "SW2"):
        fp.SetOrientationDegrees(rot)
        x0, y0, x1, y1 = bbox_g(courtyard(fp))
        fp.Move(pcbnew.VECTOR2I(MM(at[0] - (x0 + x1) / 2), MM(-(layout.Y0 + 0.05 - y0))))
    else:
        fp.SetOrientationDegrees(rot)


def fp_dump(fp):
    pads = []
    for q in fp.Pads():
        bb = q.GetBoundingBox()
        pads.append({"num": q.GetNumber(), "net": q.GetNetname(), "box": bbox_g(bb),
                     "tht": q.GetAttribute() in (pcbnew.PAD_ATTRIB_PTH, pcbnew.PAD_ATTRIB_NPTH),
                     "drill": pcbnew.ToMM(q.GetDrillSize().x)})
    kos = []
    for z in fp.Zones():
        kos.append(bbox_g(z.GetBoundingBox()))
    return {"side": "B" if fp.IsFlipped() else "F", "box": bbox_g(courtyard(fp)), "pads": pads, "keepouts": kos,
            "pos": list(G(fp.GetPosition())), "rot": fp.GetOrientationDegrees()}


def is_fixed(p):
    return p["at"] is not None or p["ref"] in layout.FIXED_EXTRA


# ---------------------------------------------------------------- zones and rule areas
def poly_zone(board, layer, pts, net=None, rule=False, priority=0, name="", pour=True, tracks=True):
    z = pcbnew.ZONE(board)
    z.SetLayer(layer)
    if rule:
        z.SetIsRuleArea(True)
        z.SetDoNotAllowZoneFills(not pour) if hasattr(z, "SetDoNotAllowZoneFills") else z.SetDoNotAllowCopperPour(not pour)
        z.SetDoNotAllowTracks(not tracks); z.SetDoNotAllowVias(not tracks)
        z.SetDoNotAllowPads(False); z.SetDoNotAllowFootprints(False)
    else:
        z.SetNet(net)
        z.SetAssignedPriority(priority)
        z.SetMinThickness(MM(0.2))
        z.SetLocalClearance(MM(0.25))
        z.SetThermalReliefGap(MM(0.3)); z.SetThermalReliefSpokeWidth(MM(0.4))
        z.SetPadConnection(pcbnew.ZONE_CONNECTION_THT_THERMAL)
        z.SetIslandRemovalMode(pcbnew.ISLAND_REMOVAL_MODE_ALWAYS)
    z.SetZoneName(name)
    ol = z.Outline()
    ol.NewOutline()
    for x, y in pts:
        v = V(x, y)
        ol.Append(v.x, v.y)
    board.Add(z)
    return z


def rect_pts(x0, y0, x1, y1):
    return [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]


def zones(board, nets):
    full = rect_pts(layout.X0, layout.Y0, layout.X1, layout.Y1)
    poly_zone(board, pcbnew.In1_Cu, full, nets["GND"], priority=0, name="GND plane")
    poly_zone(board, pcbnew.In2_Cu, full, nets["3V3"], priority=0, name="3V3 plane")
    poly_zone(board, pcbnew.B_Cu, layout.STRIP, nets["VBUS24"], priority=2, name="VBUS24 strip")
    poly_zone(board, pcbnew.F_Cu, full, nets["GND"], priority=0, name="GND pour top")
    poly_zone(board, pcbnew.B_Cu, full, nets["GND"], priority=0, name="GND pour bottom")
    lset = pcbnew.LSET.AllCuMask(4) if hasattr(pcbnew.LSET, "AllCuMask") else None
    for i, (x0, y0, x1, y1) in enumerate(layout.PRIMARY):
        e = layout.ISO
        for lay in (pcbnew.F_Cu, pcbnew.B_Cu, pcbnew.In1_Cu, pcbnew.In2_Cu):
            poly_zone(board, lay, rect_pts(x0 - e, y0 - e, x1 + e, y1 + e), rule=True, pour=False, tracks=True,
                      name="PRIMARY no-pour %d" % i)
    for lay in (pcbnew.F_Cu, pcbnew.B_Cu, pcbnew.In1_Cu, pcbnew.In2_Cu):
        poly_zone(board, lay, rect_pts(*layout.ANTENNA), rule=True, pour=False, tracks=False, name="ESP32 antenna")


# ---------------------------------------------------------------- fan-out
def inside_poly(x, y, pts):
    c = False
    n = len(pts)
    for i in range(n):
        x0, y0 = pts[i]; x1, y1 = pts[(i + 1) % n]
        if (y0 > y) != (y1 > y) and x < (x1 - x0) * (y - y0) / (y1 - y0) + x0:
            c = not c
    return c


class Copper:
    """Collision helper over pads, vias and tracks (all layers treated as one for vias)."""

    def __init__(self, board):
        self.board = board
        self.items = []   # (shape, netname, layerset)
        for fp in board.GetFootprints():
            for q in fp.Pads():
                self.items.append((q, q.GetNetname()))
        self.extra = []

    def free_via(self, x, y, d, net, clr):
        v = V(x, y)
        shp = pcbnew.SHAPE_CIRCLE(v, MM(d / 2))
        for q, n in self.items:
            if n == net and n:
                continue
            for lay in (pcbnew.F_Cu, pcbnew.B_Cu):
                if q.IsOnLayer(lay) and q.GetEffectiveShape(lay).Collide(shp, MM(clr)):
                    return False
            if q.GetAttribute() == pcbnew.PAD_ATTRIB_NPTH and q.GetEffectiveHoleShape().Collide(shp, MM(clr + 0.1)):
                return False
        for (ex, ey, ed, en, kind, w) in self.extra:
            gap = 0.25 if en == net else clr
            if kind == "via" and math.hypot(ex - x, ey - y) < (ed + d) / 2 + gap:
                return False
        for z in self.board.Zones():
            if z.GetIsRuleArea() and z.GetDoNotAllowVias() and z.Outline().Collide(v, MM(d / 2 + 0.05)):
                return False
        for fp in self.board.GetFootprints():
            for z in fp.Zones():
                if z.GetDoNotAllowVias() and z.Outline().Collide(v, MM(d / 2 + 0.05)):
                    return False
        return True

    def free_seg(self, a, b, w, net, layer, clr, own_pad):
        s = pcbnew.SHAPE_SEGMENT(V(*a), V(*b), MM(w))
        for q, n in self.items:
            if (n == net and n) or q is own_pad:
                continue
            if q.IsOnLayer(layer) and q.GetEffectiveShape(layer).Collide(s, MM(clr)):
                return False
        for fp in self.board.GetFootprints():
            for z in fp.Zones():
                if z.GetDoNotAllowTracks() and z.IsOnLayer(layer) and z.Outline().Collide(
                        pcbnew.SEG(V(*a), V(*b)), MM(w / 2 + 0.01)):
                    return False
        for (ex, ey, ed, en, kind, ww) in self.extra:
            if en != net and kind == "via":
                if pcbnew.SHAPE_CIRCLE(V(ex, ey), MM(ed / 2)).Collide(pcbnew.SEG(V(*a), V(*b)), MM(clr + w / 2)):
                    return False
        return True


def fanout(board, nets):
    cu = Copper(board)
    made, failed = [], []
    edge = 0.6
    slots = layout.SLOTS
    keep = []
    for fp in board.GetFootprints():
        for z in fp.Zones():
            keep.append(bbox_g(z.GetBoundingBox()))
    keep.append(list(layout.ANTENNA))
    for x0, y0, x1, y1 in layout.PRIMARY:
        keep.append([x0 - layout.ISO, y0 - layout.ISO, x1 + layout.ISO, y1 + layout.ISO])

    def ok_area(x, y, d):
        r = d / 2 + edge
        if not (layout.X0 + r <= x <= layout.X1 - r and layout.Y0 + r <= y <= layout.Y1 - r):
            return False
        for sx0, sy0, sx1, sy1 in slots:
            if sx0 - r < x < sx1 + r and sy0 - r < y < sy1 + r:
                return False
        for kx0, ky0, kx1, ky1 in keep:
            if kx0 - d / 2 < x < kx1 + d / 2 and ky0 - d / 2 < y < ky1 + d / 2:
                return False
        return True

    def add_via(x, y, net, d=0.6, drill=0.3):
        v = pcbnew.PCB_VIA(board)
        v.SetPosition(V(x, y)); v.SetWidth(MM(d)); v.SetDrill(MM(drill)); v.SetNet(nets[net])
        v.SetViaType(pcbnew.VIATYPE_THROUGH) if hasattr(pcbnew, "VIATYPE_THROUGH") else None
        board.Add(v)
        cu.extra.append((x, y, d, net, "via", 0))
        made.append(("via", net, x, y, d, drill))

    def add_track(a, b, w, net, layer):
        t = pcbnew.PCB_TRACK(board)
        t.SetStart(V(*a)); t.SetEnd(V(*b)); t.SetWidth(MM(w)); t.SetLayer(layer); t.SetNet(nets[net])
        board.Add(t)
        made.append(("track", net, a, b, w, layer))

    for fp in board.GetFootprints():
        for q in fp.Pads():
            net = q.GetNetname()
            if net not in layout.PLANE_NETS or q.GetAttribute() != pcbnew.PAD_ATTRIB_SMD:
                continue
            if fp.GetReference() == "U8" and q.GetNumber() == "41":
                continue   # ESP32 EP: vias in footprint
            if any(o.GetNumber() == q.GetNumber() and o.GetAttribute() == pcbnew.PAD_ATTRIB_PTH and o.GetDrillSize().x < MM(0.5)
                   for o in fp.Pads()) and q.GetSize(pcbnew.F_Cu).x > MM(2.0):
                continue   # exposed pad with thermal vias already in the footprint
            layer = pcbnew.B_Cu if fp.IsFlipped() else pcbnew.F_Cu
            px, py = G(q.GetPosition())
            bb = bbox_g(q.GetBoundingBox())
            hw, hh = (bb[2] - bb[0]) / 2, (bb[3] - bb[1]) / 2
            target = layout.PLANE_NETS[net]
            need_strip = target == "B.Cu"
            # large pads: vias inside the pad
            if min(hw, hh) * 2 >= 1.5 and max(hw, hh) * 2 >= 2.0:
                n = 0
                step = 1.1
                nx, ny = max(1, int((2 * hw - 0.4) / step)), max(1, int((2 * hh - 0.4) / step))
                for i in range(nx):
                    for j in range(ny):
                        x = px - (nx - 1) * step / 2 + i * step; y = py - (ny - 1) * step / 2 + j * step
                        if need_strip and not inside_poly(x, y, layout.STRIP):
                            continue
                        if ok_area(x, y, 0.6) and cu.free_via(x, y, 0.6, net, 0.2):
                            add_via(x, y, net); n += 1
                if n:
                    continue
            done = False
            w = max(0.15, min(0.35, 2 * min(hw, hh) - 0.06))
            near = sorted((math.hypot(ex - px, ey - py), ex, ey) for (ex, ey, ed, en, kind, ww) in cu.extra
                          if en == net and kind == "via")
            for dd, ex, ey in near:
                if dd > 1.6:
                    break
                if cu.free_seg((px, py), (ex, ey), w, net, layer, 0.2, q):
                    add_track((px, py), (ex, ey), w, net, layer)
                    done = True
                    break
            for (vd, vdr, clr) in () if done else ((0.6, 0.3, 0.2), (0.5, 0.25, 0.15)):
                for dist in (0.0, 0.2, 0.4, 0.7, 1.0, 1.4, 1.9, 2.5):
                    for ang in range(0, 360, 15):
                        ca, sa = math.cos(math.radians(ang)), math.sin(math.radians(ang))
                        ex = hw / abs(ca) if abs(ca) > 1e-6 else 1e9
                        ey = hh / abs(sa) if abs(sa) > 1e-6 else 1e9
                        r = min(ex, ey) + vd / 2 + clr + dist
                        x, y = px + r * ca, py + r * sa
                        if need_strip and not inside_poly(x, y, layout.STRIP):
                            continue
                        if not ok_area(x, y, vd):
                            continue
                        if not cu.free_via(x, y, vd, net, clr):
                            continue
                        if not cu.free_seg((px, py), (x, y), min(w, 0.25) if vd < 0.6 else w, net, layer, clr, q):
                            continue
                        add_track((px, py), (x, y), min(w, 0.25) if vd < 0.6 else w, net, layer)
                        add_via(x, y, net, vd, vdr)
                        done = True
                        break
                    if done:
                        break
                if done:
                    break
            if not done:
                failed.append((fp.GetReference(), q.GetNumber(), net))
    return made, failed


# ---------------------------------------------------------------- stages
def stage_fixed():
    board, nets = skeleton()
    dump = {}
    for p in circuit.PARTS.values():
        if is_fixed(p):
            fp = make_fp(board, nets, p)
            place_fixed(fp, p)
            dump[p["ref"]] = fp_dump(fp)
    os.makedirs(BUILD, exist_ok=True)
    json.dump(dump, open(os.path.join(BUILD, "fixed.json"), "w"), indent=1)
    print("fixed parts:", len(dump))
    for r in ("J1", "J2", "J3", "J5", "U2", "T1", "U8", "SW1"):
        d = dump[r]
        print("  %-4s side %s rot %6.1f box %s" % (r, d["side"], d["rot"], d["box"]))


def stage_full():
    board, nets = skeleton()
    place = json.load(open(os.path.join(BUILD, "place.json")))
    devs = []
    for p in circuit.PARTS.values():
        fp = make_fp(board, nets, p)
        if is_fixed(p):
            place_fixed(fp, p)
        else:
            x, y, r = place[p["ref"]]["at"][0], place[p["ref"]]["at"][1], place[p["ref"]]["rot"]
            fp.SetPosition(V(x, y)); fp.SetOrientationDegrees(r)
            pb = place[p["ref"]]["box"]
            gb = bbox_g(courtyard(fp))
            devs.append(max(abs(a - b) for a, b in zip(pb, gb)))
    print("placer/KiCad courtyard max deviation: %.3f mm" % max(devs))
    zones(board, nets)
    made, failed = fanout(board, nets)
    json.dump(made, open(os.path.join(BUILD, "fanout.json"), "w"))
    print("fan-out items:", len(made), " failed:", failed)
    board.Save(PCB)
    print("saved", PCB)


if __name__ == "__main__":
    {"fixed": stage_fixed, "full": stage_full}[sys.argv[1]]()
